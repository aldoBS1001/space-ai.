def esc(t):
    t = html.escape(t, quote=False).replace("'", "\\'").replace('"', '\\"')
    if t.startswith("@") or t.startswith("?"): t = "\\" + t
    return t
root = os.path.join(os.path.dirname(__file__), "..", "android", "app", "src", "main", "res")
for idx, folder in ((0, "values"), (1, "values-es")):
    os.makedirs(os.path.join(root, folder), exist_ok=True)
    with open(os.path.join(root, folder, "strings.xml"), "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generado por tools/gen_android_strings.py: no editar a mano. -->\n<resources>\n')
        for k, v in S.items():
            extra = ' translatable="false"' if k == "app_name" and idx == 0 else ""
            if k == "app_name" and idx == 1: continue
            f.write(f'    <string name="{k}"{extra}>{esc(v[idx])}</string>\n')
        f.write("</resources>\n")
print(len(S), "claves")
